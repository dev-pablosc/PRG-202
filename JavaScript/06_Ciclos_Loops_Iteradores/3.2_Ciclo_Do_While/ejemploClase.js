// Do while
// Sintaxis
/*
do{
    // lo qe se realiza
} while (condicion)
*/

// ejemplo
let numero = 10;
console.log('incio de loop');
do{
    console.log('Numero:' + numero);
    numero ++
} while(numero <= 5)
console.log('FIN DE DO-WHILE')

let contador = 10;
console.log('incio de loop WHILE');
while(contador <= 5) {
    console.log('El contador va en:' + contador)
    contador++ 
}
console.log('Fin de WHILE')
